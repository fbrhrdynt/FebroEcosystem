import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import http from 'node:http';
import {randomBytes,createHash} from 'node:crypto';
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'febro-files-integration-'));
Object.assign(process.env,{NODE_ENV:'test',DATA_DIR:dir,APP_URL:'http://127.0.0.1:3483',OIDC_ISSUER:'http://127.0.0.1:3470',SESSION_SECRET:randomBytes(64).toString('hex'),FEBRO_PROFILE_SERVICE_TOKEN:randomBytes(32).toString('hex'),FILES_CMS_SERVICE_TOKEN:randomBytes(32).toString('hex')});
let grant=null,authorityOnline=true,authorityCalls=0;
const token=randomBytes(32).toString('hex'),tokenHash=createHash('sha256').update(token).digest('hex');
const authority=http.createServer(async(req,res)=>{authorityCalls++;assert.equal(req.url,'/api/integrations/files/v1/grant');assert.equal(req.headers.authorization,'Bearer '+process.env.FILES_CMS_SERVICE_TOKEN);let body='';for await(const c of req)body+=c;assert.equal(JSON.parse(body).tokenHash,tokenHash);res.writeHead(!authorityOnline?503:grant?200:410,{'Content-Type':'application/json'});res.end(JSON.stringify(grant||{error:'Expired'}));});
await new Promise(r=>authority.listen(0,'127.0.0.1',r));process.env.FEBRO_CMS_API_URL='http://127.0.0.1:'+authority.address().port;
const {server,repo}=await import('../src/server.mjs');await new Promise(r=>server.listen(3483,'127.0.0.1',r));
const base='http://127.0.0.1:3483',bearer={Authorization:'Bearer '+process.env.FEBRO_PROFILE_SERVICE_TOKEN};
let remoteId;
process.env.FEBRO_ONE_FILES_SERVICE_TOKEN=randomBytes(32).toString('hex');
test('service bridge requires authentication and isolates personal files',async()=>{
 assert.equal((await fetch(base+'/api/integrations/v1/files')).status,401);
 const personal=repo.upsertAccount({sub:'personal',email:'private@example.com',name:'Private'});
 const f=repo.insertFile(personal.sub,null,'private.pdf','11111111-1111-1111-1111-111111111111',1,'hash','application/pdf');
 assert.equal((await fetch(base+'/api/integrations/v1/files/'+f.id,{headers:bearer})).status,404);
 const content=Buffer.from('%PDF-private document');
 const upload=await fetch(base+'/api/integrations/v1/files?kind=project&entry=1&name=private.pdf',{method:'POST',headers:{...bearer,'Content-Type':'application/octet-stream'},body:content});
 assert.equal(upload.status,201);remoteId=(await upload.json()).item.id;
 assert.equal((await fetch(base+'/api/integrations/v1/files/'+remoteId+'/download')).status,401);
 const download=await fetch(base+'/api/integrations/v1/files/'+remoteId+'/download',{headers:bearer});assert.equal(await download.text(),content.toString());
});
test('One identity can manage its attachments without CMS file access',async()=>{
 const headers={Authorization:'Bearer '+process.env.FEBRO_ONE_FILES_SERVICE_TOKEN,'Content-Type':'application/octet-stream'};
 assert.equal((await fetch(base+'/api/integrations/v1/files/'+remoteId+'/download',{headers})).status,404);
 const uploaded=await fetch(base+'/api/integrations/v1/files?kind=attachment&entry=11111111-1111-1111-1111-111111111111&name=one.txt',{method:'POST',headers,body:Buffer.from('One attachment')});assert.equal(uploaded.status,201);
 const id=(await uploaded.json()).item.id;
 assert.equal((await fetch(base+'/api/integrations/v1/files/'+id+'/download',{headers:bearer})).status,404);
 assert.equal(await (await fetch(base+'/api/integrations/v1/files/'+id+'/download',{headers})).text(),'One attachment');
 assert.equal((await fetch(base+'/api/integrations/v1/files?kind=cv&entry=1&name=one.txt',{method:'POST',headers,body:Buffer.from('Invalid')})).status,400);
});
test('CMS authority controls every access; IDOR, revoke, expiry, CSRF and outage fail closed',async()=>{
 grant={id:1,expiresAt:Date.now()+60000,files:[{id:7,remoteId,name:'private.pdf',caption:'Document',preview:true,download:false}]};
 assert.equal((await fetch(base+'/access/session',{method:'POST',headers:{Origin:'https://evil.example','Content-Type':'application/json'},body:JSON.stringify({token})})).status,403);
 const session=await fetch(base+'/access/session',{method:'POST',headers:{Origin:base,'Content-Type':'application/json'},body:JSON.stringify({token})});assert.equal(session.status,200);
 const headers={Cookie:session.headers.get('set-cookie').split(';')[0]};
 const listing=await fetch(base+'/access/files',{headers});assert.equal(listing.status,200);assert.equal((await listing.json()).files[0].download,false);
 assert.equal((await fetch(base+'/access/files/7/preview',{headers})).status,200);
 assert.equal((await fetch(base+'/access/files/7/download',{headers})).status,404);
 assert.equal((await fetch(base+'/access/files/8/preview',{headers})).status,404);
 assert.equal(repo.db.prepare("SELECT count(*) n FROM audit_log WHERE action='document.preview'").get().n,1);
 grant=null;assert.equal((await fetch(base+'/access/files/7/preview',{headers})).status,410);
 grant={id:1,expiresAt:Date.now()-1,files:[]};assert.equal((await fetch(base+'/access/files',{headers})).status,410);
 authorityOnline=false;assert.equal((await fetch(base+'/access/files',{headers})).status,503);
 assert.ok(authorityCalls>=7);
});
test.after(async()=>{await Promise.all([new Promise(r=>server.close(r)),new Promise(r=>authority.close(r))]);repo.close();fs.rmSync(dir,{recursive:true,force:true});});
